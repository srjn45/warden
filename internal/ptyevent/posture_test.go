var allPostures = []Posture{PostureReadOnly, PostureReadWrite, PostureAllowlisted, PostureDangerouslyExecuteAll}

func sortedNames(m map[string]*Prompt) []string {
	names := make([]string, 0, len(m))
	for n := range m {
		names = append(names, n)
	}
	sort.Strings(names)
	return names
}

// TestPromptFixtures pins the prompt wire format: every fixture prompt is
// valid, its fingerprint/instance key are consistent with its content, and the
// JSON under testdata/prompts decodes back to exactly the builder's value.
func TestPromptFixtures(t *testing.T) {
	ps := fixturePrompts()
	for _, name := range sortedNames(ps) {
		p := ps[name]
		t.Run(name, func(t *testing.T) {
			if err := p.Validate(); err != nil {
				t.Fatalf("fixture invalid: %v", err)
			}
			labels := make([]string, len(p.Options))
			for i, o := range p.Options {
				labels[i] = o.Label
			}
			if fp := Fingerprint(p.Backend, p.ShapeVersion, p.Question, labels); fp != p.Fingerprint {
				t.Errorf("fingerprint %s, recomputed %s", p.Fingerprint, fp)
			}
			if ik := InstanceKey(p.Fingerprint, p.Subject, p.Target); ik != p.InstanceKey {
				t.Errorf("instance key %s, recomputed %s", p.InstanceKey, ik)
			}
			b := mustJSON(t, p)
			golden(t, filepath.Join("prompts", name+".json"), b)
			raw, err := os.ReadFile(filepath.Join("testdata", "prompts", name+".json"))
			if err != nil {
				t.Fatal(err)
			}
			var back Prompt
			if err := json.Unmarshal(raw, &back); err != nil {
				t.Fatal(err)
			}
			if !reflect.DeepEqual(&back, p) {
				t.Errorf("round-trip mismatch:\n got %+v\nwant %+v", back, *p)
			}
		})
	}
}

type matrixCase struct {
	prompt   string
	allow    AllowlistMatch
	standing bool
	learned  bool
}

func (c matrixCase) label() string {
	al := string(c.allow)
	if al == "" {
		al = "none"
	}
	return fmt.Sprintf("%-28s allow=%-5s standing=%-5v learned=%-5v", c.prompt, al, c.standing, c.learned)
}

func matrixCases(ps map[string]*Prompt) []matrixCase {
	var cs []matrixCase
	for _, n := range sortedNames(ps) {
		for _, al := range []AllowlistMatch{AllowlistNone, AllowlistAllow, AllowlistDeny} {
			cs = append(cs, matrixCase{prompt: n, allow: al})
		}
	}
	cs = append(cs,
		matrixCase{prompt: "only_standing_allow", standing: true},
		matrixCase{prompt: "claude_bash_rm", standing: true},
		matrixCase{prompt: "learned_verified", learned: true},
		matrixCase{prompt: "learned_verified", allow: AllowlistAllow, learned: true},
	)
	return cs
}

// TestDecisionMatrix pins posture × classification → action for the whole
// fixture corpus (testdata/decisions.golden.txt) and asserts the invariants no
// row may ever break, independent of the golden.
func TestDecisionMatrix(t *testing.T) {
	ps := fixturePrompts()
	var sb strings.Builder
	sb.WriteString("# posture × classification → action (generated by TestDecisionMatrix; -update to regenerate)\n")
	for _, c := range matrixCases(ps) {
		p := ps[c.prompt]
		for _, pos := range allPostures {
			d := Decide(DecideInput{Posture: pos, Prompt: p, Allowlist: c.allow, AllowStanding: c.standing, LearnedUsable: c.learned})
			fmt.Fprintf(&sb, "%s %-24s → %-15s opt=%d rule=%s\n", c.label(), pos, d.Action, d.OptionIndex, d.Rule)
			checkInvariants(t, c, pos, p, d)
		}
	}
	golden(t, "decisions.golden.txt", []byte(sb.String()))
}

func checkInvariants(t *testing.T, c matrixCase, pos Posture, p *Prompt, d Decision) {
	t.Helper()
	where := c.label() + " " + string(pos)
	confident := Confident(p, c.learned)
	if d.Rule == "" {
		t.Errorf("%s: decision without a rule id", where)
	}
	switch d.Action {
	case ActionApprove:
		if !confident {
			t.Errorf("%s: approved an unconfident prompt", where)
		}
		if p.Class != ClassPermission {
			t.Errorf("%s: approved a %s prompt", where, p.Class)
		}
		if c.allow == AllowlistDeny {
			t.Errorf("%s: approved despite a deny rule", where)
		}
		if o := p.Options[d.OptionIndex-1]; !o.Semantic.Allows() {
			t.Errorf("%s: approve picked non-allow option %q", where, o.Label)
		}
		if pos == PostureReadOnly {
			for _, cp := range p.Capabilities {
				if cp != CapRead {
					t.Errorf("%s: read-only approved %s", where, cp)
				}
			}
		}
		if pos != PostureDangerouslyExecuteAll && p.HasCap(CapDestructive) {
			t.Errorf("%s: approved a destructive prompt outside dangerously-execute-all", where)
		}
	case ActionDeny:
		if o := p.Options[d.OptionIndex-1]; !o.Semantic.Refuses() {
			t.Errorf("%s: deny picked non-refusal option %q", where, o.Label)
		}
	case ActionAskHuman, ActionRouteDecision, ActionNeedsAttention:
		if d.OptionIndex != 0 {
			t.Errorf("%s: %s carries an option", where, d.Action)
		}
	default:
		t.Errorf("%s: unknown action %q", where, d.Action)
	}
	if !confident && d.Action != ActionNeedsAttention {
		t.Errorf("%s: unconfident prompt got %s, want needs_attention", where, d.Action)
	}
	if confident && p.Class == ClassDecision && d.Action != ActionRouteDecision {
		t.Errorf("%s: decision prompt got %s, want route_decision", where, d.Action)
	}
	if confident && p.Class == ClassPermission && pos == PostureDangerouslyExecuteAll && c.allow != AllowlistDeny && d.Action != ActionApprove {
		t.Errorf("%s: dangerously-execute-all did not approve a confident permission (%s)", where, d.Rule)
	}
}

func TestDecideEdgeCases(t *testing.T) {
	ps := fixturePrompts()
	cases := []struct {
		name string
		in   DecideInput
		want Action
		rule string
	}{
		{"invalid posture fails closed", DecideInput{Posture: "yolo", Prompt: ps["claude_read"]}, ActionNeedsAttention, RulePostureInvalid},
		{"nil prompt", DecideInput{Posture: PostureDangerouslyExecuteAll}, ActionNeedsAttention, RuleNilPrompt},
		{"invalid prompt is unconfident", DecideInput{Posture: PostureDangerouslyExecuteAll, Prompt: &Prompt{Fingerprint: "x", Class: ClassPermission, Provenance: ProvParser, Confidence: 1}}, ActionNeedsAttention, RuleUnconfident},
		{"dangerous approves trust outside workspace", DecideInput{Posture: PostureDangerouslyExecuteAll, Prompt: ps["agy_trust_foreign"]}, ActionApprove, RulePermitted},
		{"read-write trusts own worktree", DecideInput{Posture: PostureReadWrite, Prompt: ps["agy_trust_own"]}, ActionApprove, RulePermitted},
		{"read-write never trusts a foreign dir", DecideInput{Posture: PostureReadWrite, Prompt: ps["agy_trust_foreign"]}, ActionAskHuman, RuleTrustNeedsHuman},
		{"read-only never denies trust by exiting", DecideInput{Posture: PostureReadOnly, Prompt: ps["agy_trust_own"]}, ActionAskHuman, RuleTrustNeedsHuman},
		{"allowlisted destructive still asks", DecideInput{Posture: PostureAllowlisted, Prompt: ps["claude_bash_rm"], Allowlist: AllowlistAllow}, ActionAskHuman, RuleDestructiveHuman},
		{"read-only denies a write", DecideInput{Posture: PostureReadOnly, Prompt: ps["claude_edit"]}, ActionDeny, RuleForbiddenDeny},
		{"read-only cannot deny without refusal", DecideInput{Posture: PostureReadOnly, Prompt: ps["no_refusal_option"]}, ActionAskHuman, RuleForbiddenNoPath},
		{"deny rule without refusal option", DecideInput{Posture: PostureDangerouslyExecuteAll, Prompt: ps["no_refusal_option"], Allowlist: AllowlistDeny}, ActionAskHuman, RuleDenyNoPath},
		{"standing grant needs permission", DecideInput{Posture: PostureReadWrite, Prompt: ps["only_standing_allow"]}, ActionAskHuman, RuleStandingForbidden},
		{"learned unusable shape is unconfident", DecideInput{Posture: PostureDangerouslyExecuteAll, Prompt: ps["learned_verified"]}, ActionNeedsAttention, RuleUnconfident},
		{"dangerous never answers a plan approval", DecideInput{Posture: PostureDangerouslyExecuteAll, Prompt: ps["decision_plan_approval"], Allowlist: AllowlistAllow}, ActionRouteDecision, RuleDecisionPrompt},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			d := Decide(c.in)
			if d.Action != c.want || d.Rule != c.rule {
				t.Fatalf("Decide = %s/%s (%s), want %s/%s", d.Action, d.Rule, d.Reason, c.want, c.rule)
			}
		})
	}
	// Least privilege: with a once and an always option, once is chosen even
	// when standing grants are allowed.
	d := Decide(DecideInput{Posture: PostureDangerouslyExecuteAll, Prompt: ps["claude_bash_rm"], AllowStanding: true})
	if d.OptionIndex != 1 {
		t.Fatalf("picked option %d, want the one-time yes (1)", d.OptionIndex)
	}
}
