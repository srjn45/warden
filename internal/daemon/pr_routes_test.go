func TestCreatePRPushesThenOpensAndRecords(t *testing.T) {
	fs := newFakeStore()
	_ = fs.Insert(context.Background(), &agentstore.Agent{
		ID: "A-1", Workdir: "/repo/.worktrees/A-1", Subject: "Add the widget", Status: store.StatusWorking,
	})
	fl := &fakeLife{
		gitPushResult: lifecycle.PushResult{Branch: "A-1", Pushed: true},
		prResult:      lifecycle.PRResult{Branch: "A-1", Base: "main", URL: "https://github.com/o/r/pull/7", Created: true},
	}
	ts := lifeServer(t, fs, fl)
	defer ts.Close()

	resp, err := http.Post(ts.URL+"/api/v1/sessions/A-1/create-pr", "application/json", strings.NewReader(`{}`))
	require.NoError(t, err)
	defer resp.Body.Close()
	require.Equal(t, http.StatusOK, resp.StatusCode)

	require.Equal(t, "/repo/.worktrees/A-1", fl.gitPushDir, "branch is pushed before the PR")
	require.Equal(t, "/repo/.worktrees/A-1", fl.prDir, "PR is opened from the agent's own worktree")
	require.Equal(t, "Add the widget", fl.prTitle, "title comes from the agent subject")
	require.Contains(t, fl.prBody, "Generated by", "body is the markdown digest")

	var got lifecycle.PRResult
	require.NoError(t, json.NewDecoder(resp.Body).Decode(&got))
	require.True(t, got.Created)
	require.Equal(t, "https://github.com/o/r/pull/7", got.URL)

	sess, _ := fs.Get(context.Background(), "A-1")
	require.NotEmpty(t, sess.Events)
	require.Equal(t, "pr", sess.Events[len(sess.Events)-1].Type)
}

